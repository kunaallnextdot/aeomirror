"""Event ingestion for first-party website analytics — session upsert, pageview
recording, and conversion recording/deduplication. Pure DB logic, no HTTP concerns
(see app/api/routes_tracking.py for the public collector that calls this).

Idempotency contract: every pageview carries a client-generated `event_id`; every
conversion is deduplicated on (monitor_id, event_type, external_id). A session is
identified by (monitor_id, session_id) — both are client-generated by tracker.js, the
server never invents or reuses identifiers across requests.
"""
from __future__ import annotations

from datetime import datetime
from urllib.parse import urlparse

from sqlalchemy.orm import Session as DbSession

from app.db.models import AnalyticsConversion, AnalyticsPageview, AnalyticsSession, Monitor
from app.services.analytics.classification import classify_channel

_MAX_URL_LEN = 2000


def _landing_host(url: str | None) -> str | None:
    if not url:
        return None
    try:
        return urlparse(url).hostname
    except ValueError:
        return None


def get_or_create_session(db: DbSession, *, monitor: Monitor, session_id: str,
                          visitor_id: str | None, landing_url: str, referrer: str | None,
                          utm_source: str | None, utm_medium: str | None,
                          utm_campaign: str | None, now: datetime | None = None) -> AnalyticsSession:
    """Idempotent: a second call with the same (monitor, session_id) just bumps
    last_seen_at and returns the EXISTING row — first-touch attribution fields
    (channel/referrer_host/utm_*) are set once, at creation, and never overwritten."""
    now = now or datetime.utcnow()
    existing = (db.query(AnalyticsSession)
                .filter(AnalyticsSession.monitor_id == monitor.id,
                        AnalyticsSession.session_id == session_id).first())
    if existing:
        existing.last_seen_at = now
        return existing

    channel, ref_host = classify_channel(
        referrer=referrer, utm_source=utm_source, utm_medium=utm_medium,
        landing_host=_landing_host(landing_url),
    )
    is_returning = False
    if visitor_id:
        is_returning = (db.query(AnalyticsSession.id)
                        .filter(AnalyticsSession.monitor_id == monitor.id,
                                AnalyticsSession.visitor_id == visitor_id)
                        .first() is not None)

    row = AnalyticsSession(
        organization_id=monitor.organization_id, monitor_id=monitor.id,
        session_id=session_id, visitor_id=visitor_id or None, is_returning=is_returning,
        landing_url=(landing_url or "")[:_MAX_URL_LEN], referrer_host=ref_host,
        utm_source=(utm_source or None), utm_medium=(utm_medium or None),
        utm_campaign=(utm_campaign or None), channel=channel,
        started_at=now, last_seen_at=now, page_view_count=0,
    )
    db.add(row)
    db.flush()   # assign row.id without committing — caller controls the transaction
    return row


def record_pageview(db: DbSession, *, monitor: Monitor, session: AnalyticsSession,
                    event_id: str, url: str, now: datetime | None = None) -> bool:
    """Returns True if this pageview was newly recorded, False if `event_id` was
    already seen for this monitor (duplicate — e.g. a retried beacon)."""
    now = now or datetime.utcnow()
    dupe = (db.query(AnalyticsPageview.id)
            .filter(AnalyticsPageview.monitor_id == monitor.id,
                    AnalyticsPageview.event_id == event_id).first())
    if dupe:
        return False
    db.add(AnalyticsPageview(
        organization_id=monitor.organization_id, monitor_id=monitor.id,
        analytics_session_id=session.id, event_id=event_id,
        url=(url or "")[:_MAX_URL_LEN], created_at=now,
    ))
    session.page_view_count = (session.page_view_count or 0) + 1
    session.last_seen_at = now
    return True


def record_conversion(db: DbSession, *, monitor: Monitor, session: AnalyticsSession | None,
                      event_type: str, event_name: str | None, external_id: str,
                      value_cents: int | None, currency: str | None, verified: bool,
                      now: datetime | None = None) -> AnalyticsConversion:
    """Deduplicated on (monitor, event_type, external_id). A later call with
    verified=True for an already-recorded (unverified, client-reported) row upgrades
    that SAME row in place — a real server confirmation never creates a second,
    duplicate conversion record."""
    now = now or datetime.utcnow()
    existing = (db.query(AnalyticsConversion)
                .filter(AnalyticsConversion.monitor_id == monitor.id,
                        AnalyticsConversion.event_type == event_type,
                        AnalyticsConversion.external_id == external_id).first())
    if existing:
        if verified and not existing.verified:
            existing.verified = True
            if value_cents is not None:
                existing.value_cents = value_cents
            if currency:
                existing.currency = currency
            if session is not None and not existing.analytics_session_id:
                existing.analytics_session_id = session.id
            existing.updated_at = now
        return existing

    row = AnalyticsConversion(
        organization_id=monitor.organization_id, monitor_id=monitor.id,
        analytics_session_id=(session.id if session else None),
        event_type=event_type, event_name=(event_name or None)[:200] if event_name else None,
        external_id=external_id, value_cents=value_cents, currency=(currency or None),
        verified=verified, created_at=now, updated_at=now,
    )
    db.add(row)
    return row
